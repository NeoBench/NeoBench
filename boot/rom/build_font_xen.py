# What an out-of-range character becomes: a hollow block, as the console
# face does, so nothing can print as an invisible hole.
FALLBACK = [
    ".#####.",
    "#.....#",
    "#.....#",
    "#.....#",
    "#.....#",
    "#.....#",
    ".#####.",
]


def rows_for(ch):
    art = GLYPHS.get(ch, FALLBACK)
    if len(art) > H:
        raise SystemExit("glyph %r has %d rows, want %d" % (ch, len(art), H))
    out = []
    for r in art:
        if len(r) > W:
            raise SystemExit("glyph %r row %r wider than %d" % (ch, r, W))
        for c in r:
            if c not in '#.':
                raise SystemExit("glyph %r has bad pixel %r" % (ch, c))
        out.append((r + "." * W)[:W])
    while len(out) < H:
        out.append("." * W)
    return out


def byte_at(art, row):
    b = 0
    for i, c in enumerate(art[row]):
        if c == '#':
            b |= 1 << (7 - i)
    return b


def main():
    missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit("missing glyphs: %r" % "".join(missing))

    print("/* Auto-generated by build_font_xen.py -- do not edit by hand. */")
    print("#ifndef NBFONTXEN9_H")
    print("#define NBFONTXEN9_H")
    print()
    print("/* Xen at nine pixels: eight pixel advance, nine rows,")
    print(" * columns 0..6 inked and column 7 always clear. */")
    print("#define NB_XEN_H      9")
    print("#define NB_XEN_FIRST  32")
    print("#define NB_XEN_LAST   126")
    print("#define NB_XEN_BOX    95      /* fallback block, after '~'     */")
    print()
    print("static const unsigned char fontxen9[96][9] = {")
    for c in range(FIRST, LAST + 1):
        art = rows_for(chr(c))
        vals = ", ".join("0x%02x" % byte_at(art, r) for r in range(H))
        print("    { %s },   /* %s */" % (vals, chr(c)))
    art = rows_for('\0')          # the hollow block
    vals = ", ".join("0x%02x" % byte_at(art, r) for r in range(H))
    print("    { %s },   /* box */" % vals)
    print("};")
    print()
    print("#endif /* NBFONTXEN9_H */")
    return 0


if __name__ == "__main__":
    sys.exit(main())
