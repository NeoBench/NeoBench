def glyph_to_bytes(char):
    rows = GLYPHS.get(char)
    if rows is None:
        rows = GLYPHS['?']
    out = []
    for row in rows:
        assert len(row) == 8
        byte = 0
        for i, ch in enumerate(row):
            if ch == '#':
                byte |= 1 << (7 - i)
        out.append(byte)
    return out


def main():
    print("/* Auto-generated by build_font.py -- do not edit by hand. */")
    print("#ifndef NBFONT8X8_H")
    print("#define NBFONT8X8_H")
    print()
    print("static const unsigned char font8x8[256][8] = {")
    for c in range(256):
        b = glyph_to_bytes(chr(c))
        print("    { %s }," % ", ".join("0x%02x" % x for x in b))
    print("};")
    print()
    print("#endif /* NBFONT8X8_H */")
    return 0


if __name__ == "__main__":
    sys.exit(main())