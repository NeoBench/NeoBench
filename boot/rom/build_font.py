def glyph_to_bytes(char):
    rows = GLYPHS.get(char)
    if rows is None:
        rows = GLYPHS['?']
    out = []
    for row in rows:
        assert len(row) == 8
        byte = 0
        for i, ch in enumerate(row):
            if ch == '#':
                byte |= 1 << (7 - i)
        out.append(byte)
    return out


