    print("/* Auto-generated by build_font.py -- do not edit by hand. */")
    print("#ifndef NBFONT8X8_H")
    print("#define NBFONT8X8_H")
    print()
    print("static const unsigned char font8x8[256][8] = {")
    for c in range(256):
        b = glyph_to_bytes(chr(c))
        print("    { %s }," % ", ".join("0x%02x" % x for x in b))
    print("};")
    print()
    print("#endif /* NBFONT8X8_H */")
    return 0


